BY_ID = {q["id"]: q for q in QUESTIONS}
CALC_TOLERANCE = 0.15  # 小数第1位まで合っていれば正解


def check_answer(question: dict, answer) -> bool:
    if answer is None:
        return False
    if question["type"] == "calc":
        try:
            return abs(float(answer) - question["answer"]) <= CALC_TOLERANCE
        except (TypeError, ValueError):
            return False
    if question["type"] == "ox":
        return bool(answer) == question["answer"]
    return answer == question["answer"]


def correct_text(question: dict) -> str:
    """正解を文で表す（見直し用）。"""
    if question["type"] == "calc":
        return f"{question['answer']:.1f}%"
    if question["type"] == "ox":
        return "○（正しい）" if question["answer"] else "✕（まちがい）"
    return question["options"][question["answer"]]


