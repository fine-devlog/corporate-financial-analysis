# 解いた記録と、出題する問題の選び方
# --------------------------------------------------------------------------
def latest_results(history: list[dict]) -> dict:
    """問題ごとに、いちばん最近解いたときの正解/不正解を返す。history は古い順。"""
    latest = {}
    for row in history:
        if row.get("question_id") in BY_ID:
            latest[row["question_id"]] = bool(row.get("correct"))
    return latest


def wrong_question_ids(history: list[dict]) -> list[str]:
    """前回（いちばん最近）まちがえた問題。問題の並び順で返す。"""
    latest = latest_results(history)
    return [q["id"] for q in QUESTIONS if latest.get(q["id"]) is False]


def summarize(history: list[dict]) -> dict:
    latest = latest_results(history)
    return {
        "answered": len(latest),
        "total": len(QUESTIONS),
        "correct": sum(latest.values()),
        "wrong": sum(1 for v in latest.values() if not v),
        "attempts": sum(1 for r in history if r.get("question_id") in BY_ID),
    }


def pattern_progress(history: list[dict]) -> dict:
    """種類ごとに「正解済みの問題数 / 問題数」。"""
    latest = latest_results(history)
    out = {}
    for key in PATTERNS:
        ids = [q["id"] for q in QUESTIONS if q["pattern"] == key]
        out[key] = (sum(1 for i in ids if latest.get(i)), len(ids))
    return out


MIXED = "mixed"
WRONG = "wrong"


def pick_questions(history: list[dict], mode: str, n: int = 5, rng: random.Random | None = None) -> list[str]:
    """出題する問題を選ぶ。

    - まだ解いていない問題 → 前回まちがえた問題 → 正解済みの問題、の順に優先し、それぞれの中ではランダム。
      これで、くり返し解いても毎回ちがう問題が出やすくなる。
    - mode: "mixed"（企業探偵以外の全種類から）／"wrong"（前回まちがえた問題だけ）／"A"〜"H"（その種類だけ）
    - 企業探偵（H）は、1社分の手がかりを順番どおりにまとめて出す。
    """
    rng = rng or random.Random()
    latest = latest_results(history)

    if mode == WRONG:
        ids = wrong_question_ids(history)
        rng.shuffle(ids)
        return ids[:n]

    if mode == "H":
        cases = {}
        for q in QUESTIONS:
            if q["pattern"] == "H":
                cases.setdefault(q["case"], []).append(q["id"])

        def case_rank(ids):  # 未解答の手がかりがある社 → まちがいがある社 → 全問正解の社
            if any(i not in latest for i in ids):
                return 0
            return 1 if any(latest[i] is False for i in ids) else 2

        order = list(cases)
        rng.shuffle(order)
        order.sort(key=lambda c: case_rank(cases[c]))
        return cases[order[0]]

    pool = [q["id"] for q in QUESTIONS if (q["pattern"] == mode if mode in PATTERNS else q["pattern"] != "H")]
    unseen = [i for i in pool if i not in latest]
    wrong = [i for i in pool if latest.get(i) is False]
    right = [i for i in pool if latest.get(i) is True]
    for group in (unseen, wrong, right):
        rng.shuffle(group)
    return (unseen + wrong + right)[:n]
